class Workout {
  final String title;
  final String subtitle;
  final String duration;
  final String level;
  final String icon;
  final int exercises;
  final int calories;

  const Workout({
    required this.title,
    required this.subtitle,
    required this.duration,
    required this.level,
    required this.icon,
    required this.exercises,
    required this.calories,
  });
}
